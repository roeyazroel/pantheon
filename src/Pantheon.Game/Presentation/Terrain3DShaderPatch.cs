using System;

namespace Pantheon.Game.Presentation;

/// <summary>
/// Makes Terrain3D's generated terrain shader safe on drivers that do not bounds-check uniform
/// arrays, such as Mesa lavapipe (software Vulkan). Terrain3D 1.0 reads
/// <c>_region_map[pos.y * _region_map_size + pos.x]</c> before it discards positions outside the
/// region map, so a pixel with an extreme UV reads gigabytes past the uniform buffer and crashes
/// the driver. Clamping the index changes no result the shader keeps.
/// </summary>
public static class Terrain3DShaderPatch
{
    /// <summary>Region map lookup as Terrain3D 1.0 generates it.</summary>
    public const string RegionMapLookup = "_region_map[ pos.y * _region_map_size + pos.x ]";

    /// <summary>The same lookup with its index clamped to the array bounds.</summary>
    public const string ClampedRegionMapLookup = "_region_map[ clamp(pos.y * _region_map_size + pos.x, 0, _region_map.length() - 1) ]";

    /// <summary>Clamps every region map lookup in a Terrain3D shader.</summary>
    /// <param name="code">Shader code generated by Terrain3D.</param>
    /// <returns>The patched code, or <c>null</c> when the code contains no lookup in the expected form (an unsupported Terrain3D version).</returns>
    public static string? Apply(string code)
    {
        ArgumentNullException.ThrowIfNull(code);
        return code.Contains(RegionMapLookup, StringComparison.Ordinal)
            ? code.Replace(RegionMapLookup, ClampedRegionMapLookup, StringComparison.Ordinal)
            : null;
    }
}
