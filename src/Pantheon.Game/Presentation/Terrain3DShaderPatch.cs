using System;

namespace Pantheon.Game.Presentation;

/// <summary>
/// Fixes two defects in the terrain shader that Terrain3D 1.0 generates.
/// <list type="bullet">
/// <item>It reads <c>_region_map[pos.y * _region_map_size + pos.x]</c> before it discards positions
/// outside the region map. On drivers that do not bounds-check uniform arrays, such as Mesa
/// lavapipe (software Vulkan), a pixel with an extreme UV reads gigabytes past the uniform buffer
/// and crashes the driver. Clamping the index changes no result the shader keeps.</item>
/// <item>Its colour map lookup is offset by half a texel, so the last half texel along the east and
/// south edges of the outermost regions finds no region and gets the default white colour. With no
/// world background that strip shows as a pale line along the world's edge, so the lookup falls
/// back to the colour map texel under the pixel before it falls back to white.</item>
/// </list>
/// </summary>
public static class Terrain3DShaderPatch
{
    /// <summary>Region map lookup as Terrain3D 1.0 generates it.</summary>
    public const string RegionMapLookup = "_region_map[ pos.y * _region_map_size + pos.x ]";

    /// <summary>The same lookup with its index clamped to the array bounds.</summary>
    public const string ClampedRegionMapLookup = "_region_map[ clamp(pos.y * _region_map_size + pos.x, 0, _region_map.length() - 1) ]";

    /// <summary>Colour map lookup as Terrain3D 1.0 generates it.</summary>
    public const string ColorMapLookup = "vec4 color_map = region_uv.z > -1.0 ? textureLod(_color_maps, region_uv, region_mip) : COLOR_MAP_DEF;";

    /// <summary>The same lookup, trying the colour map texel under the pixel before the white default.</summary>
    public const string EdgeSafeColorMapLookup = "vec4 color_map = region_uv.z > -1.0 ? textureLod(_color_maps, region_uv, region_mip) : (index[3].z > -1 ? texelFetch(_color_maps, index[3], 0) : COLOR_MAP_DEF);";

    /// <summary>Applies both fixes to a Terrain3D shader.</summary>
    /// <param name="code">Shader code generated by Terrain3D.</param>
    /// <returns>The patched code, or <c>null</c> when either lookup is missing in the expected form (an unsupported Terrain3D version).</returns>
    public static string? Apply(string code)
    {
        ArgumentNullException.ThrowIfNull(code);
        if (!code.Contains(RegionMapLookup, StringComparison.Ordinal) || !code.Contains(ColorMapLookup, StringComparison.Ordinal))
        {
            return null;
        }

        return code
            .Replace(RegionMapLookup, ClampedRegionMapLookup, StringComparison.Ordinal)
            .Replace(ColorMapLookup, EdgeSafeColorMapLookup, StringComparison.Ordinal);
    }
}
